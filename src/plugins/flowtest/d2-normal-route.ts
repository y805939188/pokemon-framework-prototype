export function classifyFlowTestRoute(argv: readonly string[]): {kind:'inactive'} | {kind:'legacy'|'normal';mode:string} {
  const args=argv.filter(a=>a.startsWith('--ps-flow-test='));
  if(!args.length)return {kind:'inactive'};
  if(args.length!==1)throw Error('ambiguous flow-test mode');
  const mode=args[0]!.slice('--ps-flow-test='.length);
  if(mode==='d2-normal-f100')return {kind:'normal',mode};
  if(!(LEGACY_FLOW_MODES as readonly string[]).includes(mode))throw Error('unsupported flow-test mode: '+mode);
  return {kind:'legacy',mode};
}
