#!/usr/bin/env bash
# Build a runnable macOS app from the project WITHOUT MZ's Deploy (which breaks the NW.js bundle on
# Apple Silicon, see docs/step2/README.md): pristine NW.js host (ditto keeps symlinks) + an allow-listed
# app.nw + ad-hoc signature. Local/testing package only: NOT Developer ID signed, NOT notarized, and it
# contains MZ stock assets copied from the local MZ install (do not redistribute them).
#
# Usage: scripts/package-mac.sh [--with-tests] [--harden] [--identity ID] [--name NAME] [--out DIR]
#   --with-tests  keep the smoke/flow-test plugins (needed by the package test matrix)
#   --harden      sign inside-out with the hardened runtime (ad-hoc identity, see scripts/sign-mac.sh)
#   --identity ID sign with a real identity (implies --harden --timestamp); none is available on this machine yet
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MZ_APP="${MZ_APP:-$HOME/Library/Application Support/Steam/steamapps/common/RPG Maker MZ/RPGMZ.app}"
NWAPP="$MZ_APP/Contents/Resources/nwjs-mac/nwjs.app"
NAME="PokemonFrameworkPrototype"
OUT="$ROOT/build/package"
WITH_TESTS=0
HARDEN=0
IDENTITY="-"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --with-tests) WITH_TESTS=1 ;;
    --harden) HARDEN=1 ;;
    --identity) IDENTITY="$2"; HARDEN=1; shift ;;
    --name) NAME="$2"; shift ;;
    --out) OUT="$2"; shift ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
  shift
done

[[ -d "$NWAPP" ]] || { echo "NW.js host not found: $NWAPP" >&2; exit 1; }
[[ -d "$ROOT/js/engine/showdown/dist" ]] || { echo "engine not built: run scripts/build-showdown.sh" >&2; exit 1; }
[[ -f "$ROOT/js/plugins/PS_BattleFlow.js" ]] || { echo "plugins not built: run pnpm --dir src build" >&2; exit 1; }
[[ -f "$ROOT/js/engine/build/engine.cjs" ]] || { echo "engine bundle not built: run pnpm --dir src build" >&2; exit 1; }
# the compiled content must exist and be the build of exactly the current content sources (never package a stale one)
node "$ROOT/js/engine/build/content-cli.cjs" check || { echo "compiled content missing or stale: run pnpm --dir src build" >&2; exit 1; }

APP="$OUT/$NAME.app"
NW_RES="$APP/Contents/Resources/app.nw"
rm -rf "$APP"
mkdir -p "$OUT"
ditto "$NWAPP" "$APP"
rm -rf "$NW_RES"
mkdir -p "$NW_RES"

# ---- allow-list (nothing from src/, docs/, experiments/, scripts/, save/, build/, third_party/, .git) ----
EXCLUDES=(--exclude '*.map' --exclude '.DS_Store')
if [[ "$WITH_TESTS" -eq 0 ]]; then
  EXCLUDES+=(--exclude 'PS_BattleSmoke.js' --exclude 'PS_BattleFlowTest.js')
fi
cp "$ROOT/index.html" "$NW_RES/"
# the manifest name decides the per-user data folder (~/Library/Application Support/<name>): make it per game
node -e 'const fs=require("fs");const p=JSON.parse(fs.readFileSync(process.argv[1],"utf8"));p.name=process.argv[3];fs.writeFileSync(process.argv[2],JSON.stringify(p,null,2)+"\n");' "$ROOT/package.json" "$NW_RES/package.json" "$NAME"
for d in js data img audio fonts css effects icon; do
  [[ -d "$ROOT/$d" ]] && rsync -a "${EXCLUDES[@]}" "$ROOT/$d/" "$NW_RES/$d/"
done
if [[ "$WITH_TESTS" -eq 0 ]]; then
  # drop the test plugins from the manifest so the runtime does not try to load missing files
  node -e '
    const fs=require("fs"); const f=process.argv[1];
    const t=fs.readFileSync(f,"utf8");
    const m=t.match(/var \$plugins =\s*(\[[\s\S]*\]);/);
    const list=JSON.parse(m[1]).filter(p=>!/^PS_Battle(Smoke|FlowTest)$/.test(p.name));
    fs.writeFileSync(f, "// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n["+"\n"+list.map(p=>JSON.stringify(p)).join(",\n")+"\n];\n");
  ' "$NW_RES/js/plugins.js"
fi

# ---- identity ----
GIT_HEAD="$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || echo unknown)"
GIT_DIRTY="$(git -C "$ROOT" status --porcelain 2>/dev/null | wc -l | tr -d ' ')"
# Hash of the code state actually built: tracked diff + every untracked (non-ignored) file, evidence/docs excluded
# (they change while the tests run). Two packages with the same gitHead and diffSha256 were built from the same code.
EXCL=(':(exclude)experiments/step2/evidence' ':(exclude)docs')
DIFF_SHA="$( { git -C "$ROOT" diff HEAD -- . "${EXCL[@]}"; git -C "$ROOT" ls-files -o --exclude-standard -z -- . "${EXCL[@]}" | (cd "$ROOT" && xargs -0 shasum -a 256 2>/dev/null); } 2>/dev/null | shasum -a 256 | cut -d' ' -f1)"
ENGINE_SHA="$(cat "$ROOT/js/engine/showdown/SOURCE_SHA" 2>/dev/null || echo unknown)"
BUNDLE_SHA="$(shasum -a 256 "$ROOT/js/engine/build/engine.cjs" | cut -d' ' -f1)"
CONTENT_HASH="$(node -p 'require(process.argv[1]).inputsHash' "$ROOT/data/framework/content.json")"
if [[ "$HARDEN" -eq 0 ]]; then SIGNING="adhoc"; elif [[ "$IDENTITY" == "-" ]]; then SIGNING="adhoc+hardened-runtime"; else SIGNING="identity:$IDENTITY+hardened-runtime"; fi
node -e '
  const [out,head,dirty,diff,engine,tests,signing,bundle,content]=process.argv.slice(1);
  require("fs").writeFileSync(out,JSON.stringify({builtAt:new Date().toISOString(),gitHead:head,workingTreeChanges:Number(dirty),diffSha256:diff,showdownSha:engine,engineBundleSha256:bundle,contentInputsHash:content,withTests:tests==="1",signing},null,2)+"\n");
' "$NW_RES/package-info.json" "$GIT_HEAD" "$GIT_DIRTY" "$DIFF_SHA" "$ENGINE_SHA" "$WITH_TESTS" "$SIGNING" "$BUNDLE_SHA" "$CONTENT_HASH"

# ---- bundle metadata + signature ----
PLIST="$APP/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Set :CFBundleName $NAME" -c "Set :CFBundleDisplayName $NAME" -c "Set :CFBundleIdentifier io.github.pokemon-framework-prototype" "$PLIST"
xattr -cr "$APP"
if [[ "$HARDEN" -eq 1 ]]; then
  EXTRA=(); [[ "$IDENTITY" != "-" ]] && EXTRA=(--timestamp)
  "$ROOT/scripts/sign-mac.sh" "$APP" --identity "$IDENTITY" --hardened ${EXTRA[@]+"${EXTRA[@]}"} | tail -3
else
  codesign --force --deep -s - "$APP" >/dev/null 2>&1
  codesign -vv "$APP" 2>&1 | tail -2
fi

# ---- report ----
BYTES="$(du -sk "$APP" | cut -f1)"
FILES="$(find "$NW_RES" -type f | wc -l | tr -d ' ')"
APPNW_KB="$(du -sk "$NW_RES" | cut -f1)"
echo "Package: $APP"
echo "  app total ${BYTES} KB, app.nw ${APPNW_KB} KB, ${FILES} files in app.nw, withTests=$WITH_TESTS"
echo "  gitHead=$GIT_HEAD (working-tree changes: $GIT_DIRTY, diff sha256 ${DIFF_SHA:0:12}) showdown=$ENGINE_SHA signing=$SIGNING"
